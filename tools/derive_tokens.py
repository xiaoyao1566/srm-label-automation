def 是通用词(词, 通用全部):
    """判定一个候选词是不是"功能词"而不是"客户名"。

    判据：① 它本身就是通用词；② 它**含有**任何一个通用词。
    这一层是自动的 —— 不需要人去点名"哪些词算通用"：
    通用词表本身就是脚本自己的词汇表，客户简称不会撞上它。
    （实测：本项目的客户/项目简称没有一个含这些通用语素。）
    """
    if 词 in 通用全部:
        return True
    return any(len(g) >= 2 and g in 词 for g in 通用全部)


def 剥词(词):
    变过 = True
    while 变过 and 词:
        变过 = False
        for 缀 in 通用后缀:
            if len(词) > len(缀) and 词.endswith(缀):
                词 = 词[: -len(缀)]
                变过 = True
        for 缀 in 通用前缀:
            if len(词) > len(缀) and 词.startswith(缀):
                词 = 词[len(缀):]
                变过 = True
    return 词


def 派生(根目录, 广撒网=False):
    """派生敏感词表。

    ``广撒网`` 默认**关**。打开它能把召回提上去（实测专属文件名覆盖 18/34 → 23/34），
    但它取的"开头 2~4 个汉字"会把通用词**截成半截**，产出 `全流`、`本机配`、`本次运`
    这种词 —— 那些词会在仓库里刷出一堆假命中。

    这里的选择是：**宁可召回低一点，也不让闸门变成狼来了。**
    一份总在报警的报告会训练人直接忽略它，那比漏报更糟。
    所以广撒网只当**定期深度体检**用（`--广撒网`），不进日常闸门。
    真正的召回度量看 ``--自检`` 报出来的覆盖率，那是可测、可追的数字。
    """
    通用全部 = set(通用后缀) | set(通用前缀) | 通用词黑名单
    词 = set()
    根目录列表 = []
    for 当前, 子目录, 文件们 in os.walk(根目录):
        子目录[:] = [d for d in 子目录 if d not in ("__pycache__", ".git", "_旧备份_可删")]
        if os.path.relpath(当前, 根目录).count(os.sep) > 1:
            continue
        根目录列表.extend(os.path.join(当前, 名) for 名 in 文件们)

    for 路径 in 根目录列表:
        名 = os.path.splitext(os.path.basename(路径))[0]
        if not any("\u4e00" <= c <= "\u9fa5" for c in 名):
            continue  # 纯 ASCII 文件名（如 gx_print）不进词表
        c = 剥词(名).strip()
        # 只要剥完剩下的**短简称**。整条文件名（"XX内箱打印任务表"）不是简称，
        # 收进来只会让报告里的文件名与自己撞车、制造一堆假命中。
        if 2 <= len(c) <= 8 and not 是通用词(c, 通用全部) and any("\u4e00" <= ch <= "\u9fa5" for ch in c):
            词.add(c)

        if 广撒网:
            # 「广撒网」补召回：客户简称是文件名的**开头几个汉字**。
            # 但备份文件的长名字（`<客户>月份标签.btw.改份数前_<日期后缀>`）剥词后超长会被丢掉，
            # 简称就漏了 —— 实测覆盖自检报出过这种情况。
            # 所以额外取开头 2~4 个汉字当候选，再过一遍通用词过滤。
            # 代价是会有 `XX打标` 这类冗余词（噪音），所以**默认不开**。
            m = re.match(r"^[\u4e00-\u9fa5]{2,4}", 名)
            if m:
                for 长 in range(4, 1, -1):
                    片 = m.group(0)[:长]
                    if len(片) == 长 and not 是通用词(片, 通用全部):
                        词.add(片)

    # 只保留最短形式：若「南京京东方」与「南京京东方内箱」都在，留前者。
    # 短的那个一定能命中长的那所能命中的地方，留着长的纯属噪音。
    最终 = {w for w in 词 if not any(w != o and w in o for o in 词)}
    return sorted(最终, key=lambda w: (-len(w), w))


业务标记 = ("任务表", "打标签", "使用说明")
不该算的目录 = ("日志", "备份", "浏览器配置", "__pycache__", ".git", "_旧备份")
不该算的名字 = ("~$", ".bak", ".xlsx.", ".py.", "_副本", "副本_", "未覆盖")


def _像专属文件(主名):
    if any(x in 主名 for x in 不该算的名字):
        return False
    if re.match(r"^\d{8}", 主名):        # 时间戳开头的运行日志/快照
        return False
    return any(标 in 主名 for 标 in 业务标记)


def 覆盖自检(根目录, 词, 报告路径):
    """证明词表**没有削过头**：每个"客户专属文件"至少能被一个词命中。

    为什么需要它：通用词表每加一条，就多一分"把真简称也当通用词削掉"的风险。
    光看"命中数掉了多少"判断不了 —— 掉了可能只是削掉了噪音，也可能是削掉了客户名。
    所以判据换成一条硬指标：**按业务标记筛出来的专属文件名，有多少个一个词都命中不了。**

    判据用「**前缀**命中」而不是「包含」：客户简称是文件名的**开头**
    （`<客户>打印任务表`），而"包含"会把一堆通用名也算成命中，等于没查。

    ⚠️ 这个函数**只返回计数，不返回文件名列表给屏幕** ——
       文件名里就带客户简称，把它打到终端等于又泄漏一次。
       需要看清单的人自己去读那个私有文件。
    """
    专属 = []
    for 当前, 子目录, 文件们 in os.walk(根目录):
        子目录[:] = [d for d in 子目录 if d not in ("__pycache__", ".git") and not any(x in d for x in 不该算的目录)]
        if os.path.relpath(当前, 根目录).count(os.sep) > 1:
            continue
        for 名 in 文件们:
            主名 = os.path.splitext(名)[0]
            if _像专属文件(主名):
                专属.append(主名)

    未覆盖 = sorted(set(m for m in 专属 if not any(m.startswith(w) for w in 词)))
    覆盖数 = len(set(专属)) - len(未覆盖)

    # 未覆盖 ≠ 漏了客户名 —— 像「自动打标签」这种纯功能名本来就不该有词命中。
    # 所以再加一道自动判据：**把这个名字里的通用词全部剥掉，看还剩不剩东西**。
    #   剥完为空  → 它整个就是通用词拼的，没问题；
    #   还剩东西  → 那部分没人解释得了，才需要人工看。
    通用全部 = set(通用后缀) | set(通用前缀) | 通用词黑名单 | set(词)
    只剩通用词 = 0
    待人工 = []
    for m in 未覆盖:
        残 = m
        变过 = True
        while 变过 and 残:
            变过 = False
            for g in sorted(通用全部, key=len, reverse=True):
                if g and g in 残:
                    残 = 残.replace(g, "")
                    变过 = True
        残 = 残.strip("_-— " + string.digits)
        if 残:
            待人工.append("%s\t（剥掉通用词后剩下：%s）" % (m, 残))
        else:
            只剩通用词 += 1

    if 未覆盖:
        with open(报告路径, "w", encoding="utf-8") as f:
            f.write("# 这些「专属文件名」没有任何敏感词作为前缀。\n"
                    "# 判据：把通用词全部剥掉之后还剩下什么 —— 剩东西的才需要人工看。\n"
                    "# 本文件含真实文件名，只允许放私有目录。\n")
            f.write("\n".join(未覆盖) + "\n\n# ---- 剥掉通用词后仍有残留的（按可疑程度排前面）----\n")
            f.write("\n".join(待人工) + "\n")
    return 覆盖数, len(set(专属)), len(待人工)


def main():
    p = argparse.ArgumentParser(description="从文件名派生敏感词表（客户/项目简称）")
    p.add_argument("原项目目录")
    p.add_argument("-o", "--输出", required=True)
    p.add_argument("--自检", action="store_true",
                   help="顺带检查词表覆盖率：客户专属文件名里有多少个一个词都没命中")
    p.add_argument("--广撒网", action="store_true",
                   help="开启广撒网（召回更高，但会产出截断型通用词噪音；适合定期深度体检）")
    a = p.parse_args()

    词 = 派生(a.原项目目录, 广撒网=a.广撒网)
    if not 词:
        print("[警告] 一个词都没派生出来 —— 检查一下目录对不对")
        return 1

    行 = ["# 本文件含真实客户/项目名称，禁止入库、禁止外发",
          "# 由 tools/derive_tokens.py 从文件名自动派生，共 %d 条" % len(词)]
    行 += ["%d\t%s" % (i, w) for i, w in enumerate(词, 1)]

    os.makedirs(os.path.dirname(os.path.abspath(a.输出)), exist_ok=True)
    with open(a.输出, "w", encoding="utf-8") as f:
        f.write("\n".join(行) + "\n")

    # 屏幕输出刻意**不列具体词**（避免把客户名带进对话/日志），只报数量与长度分布
    分布 = {}
    for w in 词:
        分布[len(w)] = 分布.get(len(w), 0) + 1
    print("已派生敏感词 %d 条 → %s" % (len(词), a.输出))
    print("长度分布：" + "، ".join("%d字×%d" % (k, 分布[k]) for k in sorted(分布)))
    print("（词本身不在此打印，请看词表文件）")

    if a.自检:
        覆盖数, 总数, 待人工 = 覆盖自检(a.原项目目录, 词, a.输出 + ".未覆盖.txt")
        print("")
        print("[覆盖自检] 专属文件名 %d 个，其中 %d 个至少被一个词前缀命中" % (总数, 覆盖数))
        未覆盖数 = 总数 - 覆盖数
        print("[覆盖自检] 未命中 %d 个；其中「剥掉通用词后还有残留」的只有 **%d** 个"
              % (未覆盖数, 待人工))
        if 待人工:
            print("[覆盖自检] ⚠ 这 %d 个需要人工看：清单见 %s" % (待人工, a.输出 + ".未覆盖.txt"))
        else:
            print("[覆盖自检] ✔ 未命中的全都是通用词拼出来的功能名，词表没有削过头")
    return 0


if __name__ == "__main__":
    sys.exit(main())
