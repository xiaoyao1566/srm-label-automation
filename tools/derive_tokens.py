"""从原项目的**文件名**自动派生敏感词表（客户简称 / 项目简称）。

为什么需要它：
    正则只认「XX有限公司」，而真正的泄漏面往往是**两三个字的客户简称** ——
    它们藏在文件名里（`<客户>打标签.py`、`<客户>打印任务表.xlsx`）。
    靠人手写词表既容易漏，又得把客户名敲进对话。

    文件名本来就是这个项目里"客户名单的现成副本" —— 直接从中派生，一个都不会漏。

输出格式（纯文本，一行一个词）：
    第 1 行：# 本文件含真实客户/项目名称，禁止入库、禁止外发
    之后每行：序号<TAB>词

    ⚠️ 这份词表**只允许放在私有目录**（作品集仓库之外）。
    扫描器的报告引用它时只写「词表第 N 条」，不写词本身 —— 报告因此可以随便传阅。

用法：
    python tools/derive_tokens.py <原项目根目录> -o <私有目录>/敏感词表.txt
"""

import argparse
import os
import re
import string
import sys

# —— 控制台编码护栏 ——
# 中文 Windows 的 cmd / PowerShell 默认编码是 GBK，打印 ⚠ / ✔ 这类符号会直接
# UnicodeEncodeError 崩掉。这里放宽标准输出的错误策略：编不出来的符号退化成 ?，
# 绝不因为一个符号把整个派生打断。
for _流 in (sys.stdout, sys.stderr):
    try:
        _流.reconfigure(errors="replace")
    except Exception:
        pass

# 通用词：剥掉它们才能露出真正的客户/项目简称。
