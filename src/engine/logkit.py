# -*- coding: utf-8 -*-
"""日志与出错记账 —— 核心是"出错不中断 + 跑完一次性交代清楚"。

这套东西来自一个很具体的现场要求：

    现场的人不看 traceback。他要的是两句话 ——
      ① 这一趟哪儿没成；
      ② **我现在该做什么。**

所以每个失败点都必须给出「人工该做什么」，而不是把异常抛到屏幕上。
而且**一条错不能中断整批**：一颗料失败了，其余照跑，最后统一汇总。
（反过来做过一版：出错就退出。结果跑了半小时、前 20 颗料真出纸了却全被当成"确认"状态，
下次重跑又打一遍 —— 不可逆的浪费。）
"""

from __future__ import annotations

import os
import sys
import time
import traceback
from dataclasses import dataclass, field
from datetime import datetime
from typing import Callable, List, Optional


def _时刻() -> str:
    return datetime.now().strftime("%H:%M:%S")


class 记账:
    """出错账本：只记不抛。跑完由 :meth:`汇总` 一次性交代。"""

    def __init__(self) -> None:
        self.出错: List[dict] = []
        self.提示: List[dict] = []
        # 已经"真出纸并核对通过"的行 —— **跨异常保留**。
        # 这一条是血泪：脚本中途挂了，前面真打出去的标签在表里还是"待打"，
        # 重跑就会再打一遍。所以完成标记必须在确认的那一刻就记下，不能等收尾。
        self.已完成: List = []

    # -- 写 ----------------------------------------------------------------
    def 记错(self, 阶段: str, 原因: str, 标识: str = "") -> None:
        条目 = {"阶段": 阶段, "原因": 原因, "标识": 标识, "时刻": _时刻()}
        self.出错.append(条目)
        log("[出错] %s%s —— %s" % (阶段, ("/" + 标识) if 标识 else "", 原因))
        log("        → 人工该做什么：%s" % 处理建议(阶段, 原因))

    def 记提示(self, 阶段: str, 说明: str) -> None:
        self.提示.append({"阶段": 阶段, "说明": 说明, "时刻": _时刻()})
        log("[提示] %s —— %s" % (阶段, 说明))

    def 完成(self, 标识) -> None:
        if 标识 not in self.已完成:
            self.已完成.append(标识)

    # -- 读 ----------------------------------------------------------------
    def 汇总(self) -> str:
        行 = ["", "=" * 64, "本次运行汇总", "=" * 64]
        if not self.出错:
            行.append("没有遇到任何问题 ✔")
        else:
            行.append("共 %d 个问题：" % len(self.出错))
            for i, e in enumerate(self.出错, 1):
                行.append("  %2d. [%s] %s%s" % (i, e["阶段"], ("/" + e["标识"]) if e["标识"] else "", e["原因"]))
                行.append("      → 人工该做什么：%s" % 处理建议(e["阶段"], e["原因"]))
        if self.提示:
            行.append("")
            行.append("另有 %d 条提示（不算错误）：" % len(self.提示))
            for t in self.提示:
                行.append("  - [%s] %s" % (t["阶段"], t["说明"]))
        行.append("")
        行.append("确认完成：%s" % ("、".join(str(x) for x in self.已完成) if self.已完成 else "（无）"))
        行.append("=" * 64)
        return "\n".join(行)


# --------------------------------------------------------------------------
# 「人工该做什么」建议表
# --------------------------------------------------------------------------
# ⚠️ 顺序规则（踩过）：命中**第一条**就返回，所以"按原因细分"的条目
#    必须排在"按阶段"的条目**前面**，否则会被宽泛的阶段规则抢走，
#    给出一句方向完全相反的建议（真事：标签已经打出去了，却提示"别补标记"）。
建议表 = [
    # --- 按原因细分：这些必须靠前 ---
    (("写回表格", "被占用"), "先关掉被占用的那个表格文件（或换成脚本自己打开），再重跑；这一批不用重打，补标记即可。"),
    (("出纸证据", "晚到"), "证据只是晚到，**不要重打**；过 1 分钟查一次打印历史确认。"),
    (("出纸证据", "没有"), "先去打印机看一眼有没有卡纸/缺纸，再重跑这一次；**不要**重跑整批。"),
    (("张数", "不符"), "核对筛选条件是不是选到了上一批的标签；这一行**没有**标记完成，修好后重跑即可。"),
    (("验证码",), "验证码识别失败——在弹窗里手动输入这一次的验证码即可（会自动继续）。"),
    # --- 按阶段兜底 ---
    (("登录",), "确认账号口令没变、站点能打开；连续失败会弹窗要人手输验证码。"),
    (("进列表页",), "刷新页面重试；如果页面还在别的标签页，先手工切回列表页。"),
    (("读任务表",), "确认表格文件已保存、没有被别的程序独占。"),
    (("筛条件",), "核对筛选面板是不是被清空了——脚本会自动整套重填一次。"),
    (("打印",), "确认浏览器弹出的打印预览窗口没有被关掉，再重跑。"),
    (("写回状态",), "先看打印历史确认这一批**真的出纸了**，再补标记；没出纸就直接重跑。"),
    (("网络",), "检查网线/共享盘是否可达，等网络恢复后重跑。"),
]
兜底建议 = "把这一段日志原文发给管理员；在有打印历史证据之前，**不要**手工改表格状态。"


def 处理建议(阶段: str, 原因: str) -> str:
    文本 = "%s %s" % (阶段 or "", 原因 or "")
    for 关键词组, 建议 in 建议表:
        if all(k in 文本 for k in 关键词组):
            return 建议
    return 兜底建议


# --------------------------------------------------------------------------
# 日志
# --------------------------------------------------------------------------
_日志文件: Optional[object] = None
_日志路径: Optional[str] = None


def 开日志(路径: str) -> str:
    """日志落文件 + 同时打屏幕。看不到屏幕的地方（后台/双击 exe）也能留证据。"""
    global _日志文件, _日志路径
    目录 = os.path.dirname(os.path.abspath(路径))
    if 目录:
        os.makedirs(目录, exist_ok=True)
    _日志文件 = open(路径, "a", encoding="utf-8")
    _日志路径 = 路径
    log("=" * 64)
    log("开始运行（日志：%s）" % 路径)
    return 路径


def log(文本: str = "") -> None:
    行 = "[%s] %s" % (_时刻(), 文本)
    try:
        print(行, flush=True)
    except Exception:
        pass          # 没有控制台（pythonw / 双击 exe）时 print 会炸，不能因此中断
    if _日志文件:
        _日志文件.write(行 + "\n")
        _日志文件.flush()


def 关日志() -> None:
    global _日志文件
    if _日志文件:
        _日志文件.close()
        _日志文件 = None


# --------------------------------------------------------------------------
# step_guard：单步失败只记账、不中断
# --------------------------------------------------------------------------
def step_guard(账: 记账, 阶段: str, 动作: Callable, 标识: str = "",
              致命: bool = False) -> bool:
    """跑一个步骤。成功返回 True；失败记账并返回 False（默认**不中断**整批）。

    ``致命=True`` 只留给"纸已经出去了、绝不能当没事"的场景。
    """
    try:
        log("[步骤] %s%s" % (阶段, ("/" + 标识) if 标识 else ""))
        动作()
        return True
    except Exception as e:
        账.记错(阶段, "%s: %s" % (type(e).__name__, e), 标识)
        log(traceback.format_exc(limit=3))
        if 致命:
            raise
        return False
